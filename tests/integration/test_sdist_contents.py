"""What actually goes into the published artefacts.

``uv build`` builds from the working tree, and hatchling picks files by "not
gitignored", which includes untracked files: a cohort ``.bed``, a local HDF5
cache or a model trained on biobank data sitting in the checkout would be
published. ``only-include`` in pyproject.toml narrows that; this checks the
result on the artefacts themselves, because a release cannot be withdrawn from
an index in any meaningful sense.
"""

import shutil
import subprocess
import tarfile
import zipfile
from pathlib import Path

import pytest

from scripts.check_sensitive_files import check_paths

# `network`: the build resolves hatchling from an index, so this cannot run on a
# machine without internet, an HPC compute node for instance. CI runs it in a
# job of its own (see .github/workflows/ci.yml).
pytestmark = [pytest.mark.integration, pytest.mark.network]

REPO = Path(__file__).resolve().parents[2]

# In the repository, never in a release: local tool and agent state, CI, docs
# (published as a site instead) and the cluster benchmark jobs.
FORBIDDEN_TOP_LEVEL = {".claude", ".github", "docs", "benchmarks", "site", "dist"}

if shutil.which("uv") is None:
    pytest.skip("uv is needed to build the distributions", allow_module_level=True)


@pytest.fixture(scope="module")
def built(tmp_path_factory):
    out = tmp_path_factory.mktemp("dist")
    subprocess.run(
        ["uv", "build", "--out-dir", str(out)], cwd=REPO, check=True, capture_output=True
    )
    return out


@pytest.fixture(scope="module")
def sdist_members(built):
    (sdist,) = built.glob("*.tar.gz")
    with tarfile.open(sdist) as archive:
        root = f"{sdist.name[: -len('.tar.gz')]}/"
        return sorted(
            name[len(root) :]
            for name in archive.getnames()
            if name.startswith(root) and name != root
        )


@pytest.fixture(scope="module")
def wheel_members(built):
    (wheel,) = built.glob("*.whl")
    with zipfile.ZipFile(wheel) as archive:
        return sorted(archive.namelist())


@pytest.fixture(scope="module")
def tracked():
    result = subprocess.run(
        ["git", "ls-files"], cwd=REPO, check=True, capture_output=True, text=True
    )
    return set(result.stdout.split())


def _files(members):
    return [m for m in members if not m.endswith("/")]


class TestSdist:
    def test_it_ships_no_untracked_file(self, sdist_members, tracked):
        """The guard against a local build sweeping up working files.

        PKG-INFO is generated by the build and is the one expected exception.
        """
        untracked = [m for m in _files(sdist_members) if m not in tracked and m != "PKG-INFO"]

        assert untracked == []

    def test_every_file_it_ships_passes_the_sensitive_files_check(self, sdist_members):
        """The commit hook's rules, on the artefact: only the fixtures and the
        published split that .sensitive-allow names, with reasons, may ship."""
        shipped = [REPO / m for m in _files(sdist_members) if m != "PKG-INFO"]

        assert check_paths(shipped, repo_root=REPO) == []

    def test_it_ships_none_of_the_forbidden_directories(self, sdist_members):
        present = {m.split("/")[0] for m in sdist_members} & FORBIDDEN_TOP_LEVEL

        assert present == set()

    def test_it_ships_the_package_upstream_and_tests(self, sdist_members):
        assert "src/dietnet/__init__.py" in sdist_members
        assert "Dietnet_train_and_evaluate/train.py" in sdist_members
        assert "tests/unit/test_package_metadata.py" in sdist_members

    def test_it_ships_the_files_that_describe_the_release(self, sdist_members):
        expected = {"README.md", "CHANGELOG.md", "LICENSE", "NOTICE", "pyproject.toml"}

        assert expected <= set(sdist_members)


class TestWheel:
    def test_it_ships_the_type_marker(self, wheel_members):
        # PEP 561: without this, callers' type checkers ignore every annotation.
        assert "dietnet/py.typed" in wheel_members

    def test_it_ships_only_the_package(self, wheel_members):
        # Version-agnostic on purpose: pinning the dist-info name here would turn
        # every version bump into a test failure for no reason.
        top = {m.split("/")[0] for m in wheel_members}
        dist_info = {m for m in top if m.endswith(".dist-info")}

        assert len(dist_info) == 1, top
        assert top - dist_info == {"dietnet"}

    def test_it_bundles_the_upstream_code_byte_for_byte(self, built, wheel_members):
        """An installed `dietnet` must run exactly the published code."""
        (wheel,) = built.glob("*.whl")
        prefix = "dietnet/_upstream/Dietnet_train_and_evaluate/"
        shipped = [m for m in _files(wheel_members) if m.startswith(prefix)]

        assert f"{prefix}train.py" in shipped
        with zipfile.ZipFile(wheel) as archive:
            differ = [
                m
                for m in shipped
                if archive.read(m)
                != (REPO / "Dietnet_train_and_evaluate" / m[len(prefix) :]).read_bytes()
            ]
        assert differ == []

    def test_it_bundles_the_license_and_notice(self, wheel_members):
        assert any(m.endswith("licenses/LICENSE") for m in wheel_members)
        assert any(m.endswith("licenses/NOTICE") for m in wheel_members)

    def test_every_file_it_ships_is_tracked_in_git(self, wheel_members, tracked):
        """The wheel picks files by the same "not gitignored" rule as the sdist."""
        upstream = "dietnet/_upstream/"
        source = {
            m: (m[len(upstream) :] if m.startswith(upstream) else f"src/{m}")
            for m in _files(wheel_members)
            if not m.split("/")[0].endswith(".dist-info")
        }
        untracked = [m for m, path in source.items() if path not in tracked]

        assert untracked == []
